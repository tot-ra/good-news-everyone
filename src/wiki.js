export function inferReferenceRole({ title = "", meta = "", placeId = null, explicitKind = null } = {}) {
  if (explicitKind === "person" || explicitKind === "place" || explicitKind === "term") {
    return explicitKind;
  }

  if (placeId) {
    return "place";
  }

  if (PLACE_META_HINTS.test(meta) || PLACE_META_HINTS.test(title)) {
    return "place";
  }

  if (PERSON_META_HINTS.test(meta) || PERSON_META_HINTS.test(title)) {
    return "person";
  }

  return "term";
}

export function getPlaceAliases(place) {
  const fromCatalog = placeAliasCatalog[place.id] ?? [];
  return [...new Set([place.name, ...(place.aliases ?? []), ...fromCatalog].filter(Boolean))];
}

export function findPersonCatalogMatch(label = "", personId = null) {
  const normalizedPersonId = personId
    ?.trim()
    .toLowerCase()
    .replace(/^codex:/, "")
    .replace(/:\d+$/, "");
  if (normalizedPersonId) {
    const explicitMatch = peopleCatalog.find((person) => person.id === normalizedPersonId);
    if (explicitMatch) {
      return explicitMatch;
    }
  }

  const needle = label.trim().toLowerCase();
  if (!needle) {
    return null;
  }

  const catalogNames = (person) =>
    [person.name, ...(person.aliases ?? [])].map((item) => item.toLowerCase());

  // Prefer the longest exact alias so "Мария Магдалина" does not collapse to "Мария".
  let bestExact = null;
  let bestExactLength = -1;
  for (const person of peopleCatalog) {
    for (const alias of catalogNames(person)) {
      if (alias === needle && alias.length > bestExactLength) {
        bestExact = person;
        bestExactLength = alias.length;
      }
    }
  }
  if (bestExact) {
    return bestExact;
  }

  // Prefix fallback scoring:
  // - needle.startsWith(alias): query is more specific; longer alias wins
  // - alias.startsWith(needle): catalog expands a short query; do NOT prefer longer expansions
  //   (otherwise "Мария" would resolve to "Мария Магдалина")
  let bestPrefix = null;
  let bestScore = -1;
  for (const person of peopleCatalog) {
    for (const alias of catalogNames(person)) {
      let score = -1;
      if (needle.startsWith(alias)) {
        score = alias.length * 2;
      } else if (alias.startsWith(needle)) {
        score = needle.length;
      } else {
        continue;
      }
      if (score > bestScore) {
        bestPrefix = person;
        bestScore = score;
      }
    }
  }
  return bestPrefix;
}
