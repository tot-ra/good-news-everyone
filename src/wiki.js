export function inferReferenceRole({ title = "", meta = "", placeId = null, explicitKind = null } = {}) {
  if (explicitKind === "person" || explicitKind === "place" || explicitKind === "term") {
    return explicitKind;
  }

  if (placeId) {
    return "place";
  }

  if (PLACE_META_HINTS.test(meta) || PLACE_META_HINTS.test(title)) {
    return "place";
  }

  if (PERSON_META_HINTS.test(meta) || PERSON_META_HINTS.test(title)) {
    return "person";
  }

  return "term";
}

export function getPlaceAliases(place) {
  const fromCatalog = placeAliasCatalog[place.id] ?? [];
  return [...new Set([place.name, ...(place.aliases ?? []), ...fromCatalog].filter(Boolean))];
}

export function findPersonCatalogMatch(label = "", personId = null) {
  const normalizedPersonId = personId
    ?.trim()
    .toLowerCase()
    .replace(/^codex:/, "")
    .replace(/:\d+$/, "");
  if (normalizedPersonId) {
    const explicitMatch = peopleCatalog.find((person) => person.id === normalizedPersonId);
    if (explicitMatch) {
      return explicitMatch;
    }
  }

  const needle = label.trim().toLowerCase();
  if (!needle) {
    return null;
  }

  const catalogNames = (person) =>
    [person.name, ...(person.aliases ?? [])].map((item) => item.toLowerCase());
  const exactMatch = peopleCatalog.find((person) => catalogNames(person).includes(needle));
  if (exactMatch) {
    return exactMatch;
  }

  return (
    peopleCatalog.find((person) =>
      catalogNames(person).some((alias) => alias.startsWith(needle) || needle.startsWith(alias))
    ) ?? null
  );
}
